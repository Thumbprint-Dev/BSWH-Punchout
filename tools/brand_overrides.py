#!/usr/bin/env python3
"""Regenerate the GENERATED block in bswh-punchout/css/brand-bsw.css (between its start and end markers).

ModernTheme's custom.css is shared with other sites, so the Baylor theme never edits it.
Its colours are variables (set in brand-bsw.css by hand), but two things are still written
literally into its rules: corner radii, and a handful of warm one-off tints (cream stripes,
teal-tinted pills). This script re-declares exactly those properties, with the same
selectors and @media context, under BSWH values, so they win on source order with matching
specificity and nothing else in custom.css is touched.

Run it after merging ModernTheme updates into this repo:
    python3 tools/brand_overrides.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CUSTOM = ROOT / 'bswh-punchout/css/custom.css'
BRAND = ROOT / 'bswh-punchout/css/brand-bsw.css'
START = '/* ===== BSWH: GENERATED by tools/brand_overrides.py - do not edit by hand ===== */'
END = '/* ===== BSWH: END GENERATED ===== */'

# Warm ModernTheme literals -> BSWH palette (tints of BSW Light Gray / Dark Gray where a
# lighter step of the same neutral is needed). Keys are upper-case hex or normalised rgba.
COLORS = {
    # cream surfaces and placeholder stripes -> light gray family
    '#FAF8F4': '#F5F6F6', '#FCFBF8': '#FFFFFF', '#F5F3EE': '#F5F6F6', '#EFEDE6': '#ECEDED',
    '#F0EDE4': '#ECEDED', '#E8E4DA': '#D7DADB', '#ECE7DA': '#ECEDED', '#E7E1D3': '#ECEDED',
    '#E1DACB': '#DDE0E1', '#DED5C0': '#DDE0E1', '#FBEFE9': '#F5F6F6', '#E0B49A': '#959593',
    # teal / green tints (accent and success washes) -> light gray
    '#EAF3F1': '#ECEDED', '#E3F1EE': '#ECEDED', '#EAF4F2': '#ECEDED', '#E6F4EC': '#ECEDED',
    # semantic text colours -> BSW tertiary text colours (AA on white and light gray)
    '#1E7B45': '#156250', '#A85D00': '#933F10', '#A0522D': '#933F10', '#8A4B26': '#933F10',
    '#7A3D1F': '#933F10', '#8F1E18': '#B12943', '#B3261E': '#B12943',
    # warning / danger washes -> light gray
    '#FCEFD8': '#ECEDED', '#FBE7E5': '#ECEDED',
    # warm muted greys
    '#8A8378': '#5B666B', '#8A8578': '#5B666B', '#B7B2A3': '#959593', '#726D5F': '#5B666B',
    '#4A463C': '#364248', '#262420': '#364248', '#211F19': '#364248',
    '#0F6B63': '#5F277E', '#0C544E': '#4C1F65',
    # rgba tints: teal -> dark purple, warm-black shadows -> dark gray, warm scrims -> dark gray
    'rgba(15,107,99,': 'rgba(95,39,126,', 'rgba(33,31,25,': 'rgba(54,66,72,',
    'rgba(20,18,15,': 'rgba(54,66,72,', 'rgba(179,38,30,': 'rgba(177,41,67,',
}

# Corners: BSWH is square. Controls keep a small 4px so they still read as clickable; true
# circles (50%) and full pills (999px) are left alone, as are explicit zeros.
CONTROL = re.compile(r'btn|button|input|select|textarea|field|search|qty|quantity|toggle|form-control|dropdown-menu|modal', re.I)
LENGTH = re.compile(r'(?<![\w.-])(\d+(?:\.\d+)?)px')


def radius_value(value, selector):
    if '%' in value or '999' in value or 'inherit' in value or 'var(' in value:
        return None
    target = '4px' if CONTROL.search(selector) else '0'
    new = LENGTH.sub(lambda m: '0' if float(m.group(1)) == 0 else target, value)
    return new if new != value else None


def map_colors(value):
    def hexsub(m):
        return COLORS.get(m.group(0).upper(), m.group(0))
    new = re.sub(r'#[0-9A-Fa-f]{6}\b', hexsub, value)
    for k, v in COLORS.items():
        if k.startswith('rgba'):
            new = re.sub(re.escape(k).replace(',', r',\s*'), v, new)
    return new if new != value else None


def parse(css):
    """Yield (media, selector_text, declarations) for every rule, tracking one @media level."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    i, n, media_stack = 0, len(css), []
    buf = ''
    while i < n:
        c = css[i]
        if c == '{':
            head = buf.strip()
            buf = ''
            if head.startswith('@media') or head.startswith('@supports'):
                media_stack.append(head)
            elif head.startswith('@'):
                # @keyframes etc: skip the whole block
                depth, i = 1, i + 1
                while i < n and depth:
                    depth += {'{': 1, '}': -1}.get(css[i], 0)
                    i += 1
                continue
            else:
                j = css.index('}', i)
                yield (media_stack[-1] if media_stack else None, head, css[i + 1:j])
                i = j
        elif c == '}':
            if media_stack:
                media_stack.pop()
            buf = ''
        else:
            buf += c
        i += 1


def main():
    css = CUSTOM.read_text()
    out = {}  # (media, prop, value) -> [selectors]
    for media, selectors, body in parse(css):
        if selectors.strip() == ':root':
            continue
        decls = [d.strip() for d in body.split(';') if ':' in d]
        for sel in [s.strip() for s in selectors.split(',') if s.strip()]:
            for d in decls:
                prop, val = [x.strip() for x in d.split(':', 1)]
                prop = prop.lower()
                new = None
                if prop.startswith('border') and 'radius' in prop:
                    new = radius_value(val, sel)
                elif not prop.startswith('--'):
                    new = map_colors(val)
                if new is not None:
                    out.setdefault((media, prop, new), []).append(sel)

    lines = [START, '/* Same selectors as custom.css, so these win on source order alone. */']
    by_media = {}
    for (media, prop, value), sels in out.items():
        by_media.setdefault(media, []).append((prop, value, sels))
    for media in [None] + sorted(m for m in by_media if m):
        rules = by_media.get(media, [])
        if not rules:
            continue
        indent = '    ' if media else ''
        if media:
            lines.append(f'{media} {{')
        for prop, value, sels in rules:
            uniq = list(dict.fromkeys(sels))
            lines.append(indent + (',\n' + indent).join(uniq) + ' {')
            lines.append(f'{indent}    {prop}: {value};')
            lines.append(indent + '}')
        if media:
            lines.append('}')

    # Replace what's between the markers. The block sits above the hand-written Components
    # section on purpose, so those rules keep winning over the generated ones.
    brand = BRAND.read_text()
    if START not in brand or END not in brand:
        sys.exit('brand-bsw.css is missing the GENERATED start/end markers')
    head, rest = brand.split(START, 1)
    tail = rest.split(END, 1)[1]
    BRAND.write_text(head + '\n'.join(lines) + '\n' + END + tail)
    print(f'{sum(len(v) for v in out.values())} selector overrides in {len(out)} rules', file=sys.stderr)


if __name__ == '__main__':
    main()
